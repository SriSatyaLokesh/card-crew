#!/usr/bin/env node
// Regenerates supabase/seed.sql from backend/src/catalog/card-catalog.seed.ts — the card
// catalog data and use-case inference logic stay defined in one place (the TS source);
// this just re-derives the Postgres INSERT statements from it. Run after editing the TS
// seed list:
//
//   node scripts/generate-catalog-seed.js
//
// Ponytail note: this parses the TS file with a regex rather than pulling in a TS
// compiler for a one-shot code-gen script — the source array's shape is stable and
// simple, and the alternative is a build step nobody else in this repo needs.
"use strict";

const fs = require("fs");
const path = require("path");

const repoRoot = path.join(__dirname, "..");
const srcPath = path.join(repoRoot, "backend/src/catalog/card-catalog.seed.ts");
const outPath = path.join(repoRoot, "supabase/seed.sql");

const src = fs.readFileSync(srcPath, "utf8");

const arrMatch = src.match(/const CARD_CATALOG_SEED: CardSeedTuple\[\] = \[([\s\S]*?)\n\];/);
if (!arrMatch) throw new Error(`could not locate CARD_CATALOG_SEED array in ${srcPath}`);
const arrBody = arrMatch[1];

const rowRe =
  /\[\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]+)",\s*(null|"[^"]*"),\s*(true|false)\s*\]/g;
const rows = [];
let m;
while ((m = rowRe.exec(arrBody))) {
  const [, id, issuer, product_name, card_type, card_category, network, segment, variantRaw, upiRaw] = m;
  const variant = variantRaw === "null" ? null : variantRaw.slice(1, -1);
  rows.push({ id, issuer, product_name, card_type, card_category, network, segment, variant, upi_enabled: upiRaw === "true" });
}
if (rows.length === 0) throw new Error("no rows parsed — has the CARD_CATALOG_SEED tuple shape changed?");

// Mirrors inferUseCases() in card-catalog.seed.ts verbatim. Keep these two in sync by hand
// if the TS logic changes — there's no shared module between a Vite/Node app and a
// standalone codegen script worth introducing for eight regexes.
function inferUseCases(issuer, productName, cardCategory, upiEnabled) {
  const searchable = `${issuer} ${productName}`.toLowerCase();
  const useCases = new Set([cardCategory === "debit" ? "daily-banking" : "general-spend"]);
  if (upiEnabled) useCases.add("upi");
  if (/travel|atlas|air india|ixigo|scapia|world safari|platinum|reserve|emeralde|infinia|wealth|magnus/i.test(searchable))
    useCases.add("travel");
  if (/cashback|cash back|ace|millennia|swiggy|amazon|flipkart|airtel|live\+|smart/i.test(searchable))
    useCases.add("cashback");
  if (/fuel|indianoil|bpcl|hpcl/i.test(searchable)) useCases.add("fuel");
  if (/dining|eazydiner|tata neu|myntra|swiggy|lifestyle|coral|rubyx/i.test(searchable)) useCases.add("lifestyle");
  if (/irctc|railway/i.test(searchable)) useCases.add("railway");
  if (/debit|daily/i.test(searchable) || cardCategory === "debit") useCases.add("daily-banking");
  return [...useCases];
}

function sqlStr(s) {
  return "'" + String(s).replace(/'/g, "''") + "'";
}
function slug(s) {
  return s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

// catalog_items is unique on (issuer_id, item_type, name) -- it has no network column,
// deliberately, since it's the generic table shared by every future resource type, not
// just cards. A handful of real products are only distinguishable by network (e.g. HDFC
// issues "Tata Neu Infinity" as both a RuPay and a Visa card) -- disambiguate those names
// with a network suffix so they land as two catalog_items rows instead of silently
// colliding into one (found by running `supabase db reset` and comparing row counts
// against source row counts -- see supabase/README.md).
const byIssuerAndName = new Map();
for (const r of rows) {
  const key = `${r.issuer}|${r.product_name}`;
  if (!byIssuerAndName.has(key)) byIssuerAndName.set(key, []);
  byIssuerAndName.get(key).push(r);
}
for (const group of byIssuerAndName.values()) {
  if (group.length > 1) {
    for (const r of group) r.product_name = `${r.product_name} (${r.network})`;
  }
}

const issuers = new Map();
const networks = new Map();
const useCaseSet = new Set();
const rowsWithUseCases = rows.map((r) => {
  issuers.set(slug(r.issuer), r.issuer);
  networks.set(slug(r.network), r.network);
  const useCases = inferUseCases(r.issuer, r.product_name, r.card_category, r.upi_enabled);
  useCases.forEach((u) => useCaseSet.add(u));
  return { ...r, useCases };
});

const lines = [];
lines.push("-- Card Crew catalog seed data.");
lines.push("-- Generated by scripts/generate-catalog-seed.js from backend/src/catalog/card-catalog.seed.ts.");
lines.push("-- Regenerate rather than hand-edit: node scripts/generate-catalog-seed.js");
lines.push("");
lines.push("-- Country fixed at 'IN' (matches the original seed's scope).");
lines.push("");

lines.push("insert into issuers (slug, name, country) values");
lines.push(
  [...issuers.entries()].map(([s, n], i, arr) => `  (${sqlStr(s)}, ${sqlStr(n)}, 'IN')${i === arr.length - 1 ? "" : ","}`).join("\n") +
    "\non conflict (slug) do update set name = excluded.name;"
);
lines.push("");

lines.push("insert into card_networks (slug, name) values");
lines.push(
  [...networks.entries()].map(([s, n], i, arr) => `  (${sqlStr(s)}, ${sqlStr(n)})${i === arr.length - 1 ? "" : ","}`).join("\n") +
    "\non conflict (slug) do update set name = excluded.name;"
);
lines.push("");

lines.push("insert into use_cases (slug) values");
lines.push(
  [...useCaseSet]
    .sort()
    .map((u, i, arr) => `  (${sqlStr(u)})${i === arr.length - 1 ? "" : ","}`)
    .join("\n") + "\non conflict (slug) do nothing;"
);
lines.push("");

lines.push("-- catalog_items + catalog_cards, one CTE-chained upsert per card so re-running the seed is idempotent");
for (const r of rowsWithUseCases) {
  const useCaseValues = r.useCases.map((u) => sqlStr(u)).join(", ");
  lines.push(`-- legacy id: ${r.id}`);
  lines.push(`with item as (`);
  lines.push(`  insert into catalog_items (item_type, issuer_id, name, country, active)`);
  lines.push(`  select 'card', i.id, ${sqlStr(r.product_name)}, 'IN', true`);
  lines.push(`  from issuers i where i.slug = ${sqlStr(slug(r.issuer))}`);
  lines.push(`  on conflict (issuer_id, item_type, name) do update set active = true`);
  lines.push(`  returning id`);
  lines.push(`), card as (`);
  lines.push(`  insert into catalog_cards (catalog_item_id, card_type, card_category, network_id, segment, variant, upi_enabled)`);
  lines.push(
    `  select item.id, ${sqlStr(r.card_type)}, ${sqlStr(r.card_category)}, n.id, ${sqlStr(r.segment)}, ${
      r.variant === null ? "null" : sqlStr(r.variant)
    }, ${r.upi_enabled}`
  );
  lines.push(`  from item, card_networks n where n.slug = ${sqlStr(slug(r.network))}`);
  lines.push(
    `  on conflict (catalog_item_id) do update set card_type = excluded.card_type, card_category = excluded.card_category, network_id = excluded.network_id, segment = excluded.segment, variant = excluded.variant, upi_enabled = excluded.upi_enabled`
  );
  lines.push(`  returning catalog_item_id`);
  lines.push(`)`);
  lines.push(`insert into catalog_card_use_cases (catalog_item_id, use_case_id)`);
  lines.push(`select card.catalog_item_id, uc.id from card, use_cases uc where uc.slug in (${useCaseValues})`);
  lines.push(`on conflict do nothing;`);
  lines.push("");
}

fs.writeFileSync(outPath, lines.join("\n"), "utf8");
console.log(`wrote ${outPath}: ${rows.length} cards, ${issuers.size} issuers, ${networks.size} networks, ${useCaseSet.size} use cases`);
